test_that("read_ci reproduces the 'conclusion holds for' column of Table 2", {
  expect_equal(read_ci(6.54, 14.76, 10.65)$importance_holds_for, 6.54)
  expect_equal(read_ci(6.2, 19.6, 12.9)$importance_holds_for, 6.2)
  expect_equal(read_ci(0.12, 0.74, 0.43)$equivalence_holds_for, 0.74)
  expect_equal(read_ci(-6.8, 6.5, -0.2)$equivalence_holds_for, 6.8)
  expect_true(is.na(read_ci(-6.8, 6.5, -0.2)$importance_holds_for))
  expect_equal(read_ci(-4.9, 2.1, -1.38)$noninferiority_holds_for, 4.9)
  expect_equal(read_ci(-1.4, 7.2, 2.9)$equivalence_holds_for, 7.2)
  expect_equal(read_ci(4.92, 10.17, 7.54)$importance_holds_for, 4.92)
})
test_that("read_ci patterns use thresholds set outside the data", {
  expect_match(read_ci(6.54, 14.76, threshold = 6)$pattern, "^Clinically important")
  expect_equal(read_ci(-6.8, 6.5, threshold = 8)$pattern, "Practically equivalent")
  expect_equal(read_ci(4.92, 10.17, threshold = 10)$pattern, "Real, importance unclear")
  expect_equal(read_ci(-1.4, 7.2, threshold = 10)$pattern, "Practically equivalent")
  expect_true(is.na(read_ci(-1, 1)$pattern))
  expect_equal(read_ci(-2, 1, higher_is_better = FALSE)$noninferiority_holds_for, 1)
  expect_output(print(read_ci(-4.9, 2.1)), "no test against a post hoc threshold")
})
